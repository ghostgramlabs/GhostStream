def fix_locale(locale_name, base_res_path):
    # 1. Sync structure first (this also handles escaping)
    loc_sync.sync_locale(locale_name, base_res_path)
    
    locale_path = os.path.join(base_res_path, f'values-{locale_name}', 'strings.xml')
    if not os.path.exists(locale_path):
        return

    # 2. Parse English for order
    en_path = os.path.join(base_res_path, 'values', 'strings.xml')
    tree_en = ET.parse(en_path)
    root_en = tree_en.getroot()
    
    # 3. Parse current Locale (after sync)
    tree_loc = ET.parse(locale_path)
    root_loc = tree_loc.getroot()
    loc_data = {}
    for child in root_loc:
        name = child.get('name')
        if child.tag == 'string':
            loc_data[name] = child.text
        elif child.tag == 'plurals':
            items = {}
            for item in child:
                items[item.get('quantity')] = item.text
            loc_data[name] = items

    # 4. Create new root to preserve order and inject fixes
    new_root = ET.Element('resources')
    data = TRANSLATIONS.get(locale_name, {})
    
    for child_en in root_en:
        name = child_en.get('name')
        tag = child_en.tag
        
        # Determine value (Fix > Existing > English)
        if name in data:
            val = data[name]
        elif name in loc_data:
            val = loc_data[name]
        else:
            # English fallback
            if tag == 'string':
                val = child_en.text
            else:
                val = {item.get('quantity'): item.text for item in child_en}

        # Create element
        if tag == 'string':
            el = ET.SubElement(new_root, 'string', name=name)
            el.text = loc_sync.escape_android_string(val) if isinstance(val, str) else val
        else:
            el = ET.SubElement(new_root, 'plurals', name=name)
            if isinstance(val, dict):
                for q, t in val.items():
                    item = ET.SubElement(el, 'item', quantity=q)
                    item.text = loc_sync.escape_android_string(t)
            else:
                # Fallback if somehow it wasn't a dict
                for item_en in child_en:
                    item = ET.SubElement(el, 'item', quantity=item_en.get('quantity'))
                    item.text = loc_sync.escape_android_string(item_en.text)

    # 5. Save with pretty print
    xml_str = ET.tostring(new_root, encoding='utf-8')
    pretty_xml = minidom.parseString(xml_str).toprettyxml(indent="    ")
    
    with open(locale_path, "w", encoding="utf-8") as f:
        f.write(pretty_xml)
    print(f"Fixed {locale_name}")

if __name__ == "__main__":
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    res_path = os.path.join(base_dir, 'core', 'resources', 'src', 'main', 'res')
    for loc in ['es', 'fr', 'de', 'it', 'pt', 'pt-rBR', 'ar', 'hi', 'ru', 'ja', 'zh-rCN', 'zh-rTW', 'ko', 'nl', 'sv', 'el', 'tr', 'id', 'in', 'vi', 'th', 'af', 'ta', 'te', 'ml']:
        fix_locale(loc, res_path)
